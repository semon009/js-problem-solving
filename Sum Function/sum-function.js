/**
 * Problem: Sum Function
 * 
 * Description:
 * Create the 'sum' function that takes two numbers as parameters and returns their sum.
 * 
 * Example:
 * sum(3, 5) -> returns 8
 * sum(10, 20) -> returns 30
 */

// Solution: Function that accepts two parameters and returns their sum
function sum(x, y) {
  return x + y;
}

