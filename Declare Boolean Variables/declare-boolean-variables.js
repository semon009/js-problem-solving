/**
 * Problem: Declare Boolean Variables
 * 
 * Description:
 * Declare a variable called 'bool1' and set its value to true. 
 * Declare a second variable named 'bool2' and set its value to false.
 */

// Solution:
let bool1 = true;
let bool2 = false;

// Testing the solution
console.log("bool1:", bool1); // Outputs: bool1: true
console.log("bool2:", bool2); // Outputs: bool2: false
