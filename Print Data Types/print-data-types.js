/**
 * Problem: Print Data Types
 * 
 * Description:
 * Write code that prints the data type of the following three values to the console:
 * "an apple", 63, and 19.3.
 * 
 * Expected Output:
 * string
 * number
 * number
 */

// Solution: Using the typeof operator to check data types
console.log(typeof("an apple"));
console.log(typeof(63));
console.log(typeof(19.3));
