/**
 * Problem: Pub Age Checker
 * 
 * Description:
 * Check if a person is allowed to enter a pub based on their age.
 * Set 'age' to 18 and evaluate whether 'age' is less than 18.
 */

// Solution:
let age = 18;
let condition = age < 18;

if (condition) {
    console.log("Sorry, but you are a minor.");
} else {
    console.log("That's ok. You can enter the pub.");
}
